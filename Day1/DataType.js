// Data types in JavaScript
// JavaScript has several data types, including:

// 1. Primitive Data Types
// - String: Represents a sequence of characters. Example: "Hello", 'World'
// - Number: Represents both integer and floating-point numbers. Example: 42, 3.14
// - Boolean: Represents a logical entity that can have two values: true or false.
// - Null: Represents the intentional absence of any object value. It is a primitive value that represents the null or empty value.
// - Undefined: Represents a variable that has been declared but has not been assigned a value.

// 2. Non-Primitive Data Types
// - Object: Represents a collection of properties and methods. It is a complex data type that can hold multiple values and functions.
// - Array: A special type of object that is used to store multiple values in a single variable. It is an ordered collection of items.

// Example of using different data types
let name = "Alice"; // String
let age = 30; // Number
let isStudent = false; // Boolean
let address = null; // Null
let phoneNumber; // Undefined

console.log(name); // Output: Alice
console.log(age); // Output: 30
console.log(isStudent); // Output: false
console.log(address); // Output: null
console.log(phoneNumber); // Output: undefined

// Example of using an object
